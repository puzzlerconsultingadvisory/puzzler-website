// WEB-01 / WEB-02: favicon set and touch icons derived from the exact BR-01 mark file.
//   /favicon.svg           the BR-01 polygons, byte-for-byte, on a white tile (Brand Standards §8.1: full-colour mark on white)
//   /favicon-32.png, /favicon-16.png, /favicon.ico (16/32/48)   raster fallbacks
//   /apple-touch-icon.png (180)  /icon-192.png  /icon-512.png   touch + manifest icons
// The mark is never redrawn: rasters are Chromium renders of the unmodified SVG file; favicon.svg copies its
// <polygon> elements verbatim (same 1024 viewBox, no transform). Run from tools/: node build-favicons.mjs
import { chromium } from 'playwright';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const MARK = resolve(root, 'assets/brand/puzzler_logo_4piece.svg');
const svgText = readFileSync(MARK, 'utf8');
const polygons = svgText.match(/<polygon[^>]*\/>/g) || [];
if (polygons.length !== 4) { console.error(`expected 4 polygons in BR-01, found ${polygons.length}`); process.exit(1); }

// Padding is a fraction of the tile; the mark file already carries a 48/1024 margin inside its own viewBox.
const RASTERS = [
  { out: 'favicon-16.png', size: 16, pad: 0 },
  { out: 'favicon-32.png', size: 32, pad: 0 },
  { out: 'favicon-48.png', size: 48, pad: 0, icoOnly: true },
  { out: 'apple-touch-icon.png', size: 180, pad: 0.10 },
  { out: 'icon-192.png', size: 192, pad: 0.10 },
  { out: 'icon-512.png', size: 512, pad: 0.10 },
];

// favicon.svg: white tile + the untouched polygons. Modern browsers pick this over the raster fallbacks.
{
  const svg = [
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" width="1024" height="1024" role="img" aria-label="Puzzler Consulting and Advisory Services four-piece mark">',
    '  <!-- Generated by tools/build-favicons.mjs from assets/brand/puzzler_logo_4piece.svg (BR-01). Polygons are copied verbatim; do not edit. -->',
    '  <rect width="1024" height="1024" fill="#FFFFFF"/>',
    ...polygons.map((p) => `  ${p}`),
    '</svg>',
    '',
  ].join('\n');
  writeFileSync(resolve(root, 'favicon.svg'), svg);
}

const browser = await chromium.launch();
const pngs = {};
for (const r of RASTERS) {
  const page = await browser.newPage({ viewport: { width: r.size, height: r.size }, deviceScaleFactor: 1 });
  const inner = Math.round(r.size * (1 - 2 * r.pad));
  const off = Math.round((r.size - inner) / 2);
  await page.setContent(`<!doctype html><html><body style="margin:0;background:#FFFFFF;width:${r.size}px;height:${r.size}px;overflow:hidden">
    <img src="data:image/svg+xml;base64,${Buffer.from(svgText).toString('base64')}" style="position:absolute;left:${off}px;top:${off}px;width:${inner}px;height:${inner}px;display:block"></body></html>`);
  await page.waitForFunction(() => { const i = document.querySelector('img'); return i.complete && i.naturalWidth > 0; });
  const buf = await page.screenshot({ type: 'png', omitBackground: false });
  pngs[r.size] = buf;
  if (!r.icoOnly) writeFileSync(resolve(root, r.out), buf);
  await page.close();
}
await browser.close();

// favicon.ico with PNG-compressed 16/32/48 entries (ICONDIR + ICONDIRENTRY[] + image data).
{
  const sizes = [16, 32, 48];
  const header = Buffer.alloc(6);
  header.writeUInt16LE(0, 0); header.writeUInt16LE(1, 2); header.writeUInt16LE(sizes.length, 4);
  const entries = []; const datas = [];
  let offset = 6 + 16 * sizes.length;
  for (const s of sizes) {
    const data = pngs[s];
    const e = Buffer.alloc(16);
    e.writeUInt8(s >= 256 ? 0 : s, 0); e.writeUInt8(s >= 256 ? 0 : s, 1); e.writeUInt8(0, 2); e.writeUInt8(0, 3);
    e.writeUInt16LE(1, 4); e.writeUInt16LE(32, 6); e.writeUInt32LE(data.length, 8); e.writeUInt32LE(offset, 12);
    offset += data.length; entries.push(e); datas.push(data);
  }
  writeFileSync(resolve(root, 'favicon.ico'), Buffer.concat([header, ...entries, ...datas]));
}
console.log('wrote favicon.svg favicon.ico favicon-16.png favicon-32.png apple-touch-icon.png icon-192.png icon-512.png');
