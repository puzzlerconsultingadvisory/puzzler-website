// Generates the Blueprint Puzzle hero layers (BP-02 field, BP-04 connection overlay)
// and injects the overlay inline into index.html between the bp-connections markers,
// so the file and the page never drift. Run: npm run build:hero
//
// Direction (handoff §4, reference BP-01): restrained blueprint grid, measurement marks,
// interlocking structural piece outlines, connection states. Navy / teal / steel tones,
// text-free, no glow. The centre piece carries a slightly stronger line weight.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const dir = resolve(root, 'website-assets/blueprint/hero');

// 3×3 pieces, 200 units each, inside a 1200×800 field.
const X0 = 300, Y0 = 100, S = 200, N = 3;
const K = 0.82; // tab scale
const NECK = 12 * K, HEAD = 34 * K, DEPTH = 60 * K, H = (200 - 44 * K) / 2; // tab geometry

// Horizontal edge segment from (x,y) to (x+S,y); dir = -1 tab up, +1 tab down.
function hEdge(x, y, dir) {
  const d = dir;
  const c = (...v) => v.map((n) => Math.round(n * 100) / 100).join(' ');
  return `M${x} ${y}h${H}c${c(0, 10 * K * d, -NECK, 16 * K * d, -NECK, 28 * K * d)}c${c(0, 20 * K * d, 15 * K, 32 * K * d, HEAD, 32 * K * d)}c${c(19 * K, 0, HEAD, -12 * K * d, HEAD, -32 * K * d)}c${c(0, -12 * K * d, -NECK, -18 * K * d, -NECK, -28 * K * d)}h${H}`;
}
// Vertical edge segment from (x,y) to (x,y+S); dir = -1 tab left, +1 tab right.
function vEdge(x, y, dir) {
  const d = dir;
  const c = (...v) => v.map((n) => Math.round(n * 100) / 100).join(' ');
  return `M${x} ${y}v${H}c${c(10 * K * d, 0, 16 * K * d, -NECK, 28 * K * d, -NECK)}c${c(20 * K * d, 0, 32 * K * d, 15 * K, 32 * K * d, HEAD)}c${c(0, 19 * K, -12 * K * d, HEAD, -32 * K * d, HEAD)}c${c(-12 * K * d, 0, -18 * K * d, -NECK, -28 * K * d, -NECK)}v${H}`;
}

const interior = [];
const nodes = [];
// interior vertical edges: x = X0+S, X0+2S ; rows 0..2
for (let c = 1; c < N; c++) for (let r = 0; r < N; r++) {
  const dir = (c + r) % 2 === 0 ? 1 : -1;
  interior.push(vEdge(X0 + c * S, Y0 + r * S, dir));
  nodes.push([X0 + c * S + dir * (DEPTH / 2), Y0 + r * S + S / 2]);
}
// interior horizontal edges: y = Y0+S, Y0+2S ; cols 0..2
for (let r = 1; r < N; r++) for (let c = 0; c < N; c++) {
  const dir = (c + r) % 2 === 0 ? -1 : 1;
  interior.push(hEdge(X0 + c * S, Y0 + r * S, dir));
  nodes.push([X0 + c * S + S / 2, Y0 + r * S + dir * (DEPTH / 2)]);
}

const ticks = (from, to, step, major, axis, base) => {
  const out = [];
  for (let v = from; v <= to; v += step) {
    const big = (v - from) % major === 0;
    const len = big ? 8 : 4;
    out.push(axis === 'x' ? `M${v} ${base - len}V${base + len}` : `M${base - len} ${v}H${base + len}`);
  }
  return out.join('');
};

const field = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1200 800" width="1200" height="800" preserveAspectRatio="xMidYMid meet">
  <!--
    BP-02 Hero blueprint field. Generated by tools/build-hero-layers.mjs. Do not edit by hand.
    Text-free: drafting rulers, corner marks, interlocking structural piece outlines, and open
    connection states. Rendered on Puzzler Navy by the page. Scales with "meet" so nothing is cropped.
  -->
  <g id="field-marks" fill="none" stroke="#FFFFFF" stroke-opacity="0.36" stroke-width="1" stroke-linecap="square">
    <path d="M${X0} 64H${X0 + N * S}"/>
    <path d="${ticks(X0, X0 + N * S, 25, 100, 'x', 64)}"/>
    <path d="M232 ${Y0}V${Y0 + N * S}"/>
    <path d="${ticks(Y0, Y0 + N * S, 25, 100, 'y', 232)}"/>
    <path d="M968 ${Y0}V${Y0 + N * S}M960 ${Y0}H976M960 ${Y0 + N * S}H976"/>
  </g>
  <g id="field-corners" fill="none" stroke="#30A396" stroke-opacity="0.9" stroke-width="2" stroke-linecap="square">
    <path d="M${X0 - 10} ${Y0 + 30}V${Y0 - 10}H${X0 + 30}"/>
    <path d="M${X0 + N * S - 30} ${Y0 - 10}H${X0 + N * S + 10}V${Y0 + 30}"/>
    <path d="M${X0 + N * S + 10} ${Y0 + N * S - 30}V${Y0 + N * S + 10}H${X0 + N * S - 30}"/>
    <path d="M${X0 + 30} ${Y0 + N * S + 10}H${X0 - 10}V${Y0 + N * S - 30}"/>
  </g>
  <g id="field-perimeter" fill="none" stroke="#FFFFFF" stroke-opacity="0.6" stroke-width="1.5">
    <rect x="${X0}" y="${Y0}" width="${N * S}" height="${N * S}"/>
  </g>
  <g id="field-pieces" fill="none" stroke="#FFFFFF" stroke-opacity="0.34" stroke-width="1.25" stroke-linejoin="round">
    <path d="${interior.join('')}"/>
  </g>
  <g id="field-centre" fill="none" stroke="#FFFFFF" stroke-opacity="0.85" stroke-width="2" stroke-linejoin="round">
    <path d="${vEdge(X0 + S, Y0 + S, 1)}${vEdge(X0 + 2 * S, Y0 + S, -1)}${hEdge(X0 + S, Y0 + S, 1)}${hEdge(X0 + S, Y0 + 2 * S, -1)}"/>
  </g>
  <g id="field-nodes-open" fill="#1A1A2E" stroke="#FFFFFF" stroke-opacity="0.6" stroke-width="1.5">
    ${nodes.map(([x, y]) => `<circle cx="${x}" cy="${y}" r="6"/>`).join('')}
  </g>
</svg>
`;

// Connection overlay: paths run along structural lines into the centre piece and settle.
const cx = X0 + S + S / 2, cy = Y0 + S + S / 2; // centre of centre piece (600,400)
const overlayShapes = `  <g fill="none" stroke="#30A396" stroke-width="2.5" stroke-linecap="round" stroke-linejoin="round">
    <path class="trace t1" pathLength="1" d="M${X0} ${Y0 + S - DEPTH / 2}H${cx}"/>
    <path class="trace t2" pathLength="1" d="M${X0 + N * S} ${Y0 + 2 * S + DEPTH / 2}H${cx}"/>
    <path class="trace t3" pathLength="1" d="M${X0 + S + DEPTH / 2} ${Y0}V${cy}"/>
    <path class="trace t4" pathLength="1" d="M${X0 + 2 * S - DEPTH / 2} ${Y0 + N * S}V${cy}"/>
  </g>
  <g fill="#30A396" stroke="#1A1A2E" stroke-width="1.5">
    <circle class="join j1" cx="${X0 + S + S / 2}" cy="${Y0 + S - DEPTH / 2}" r="7"/>
    <circle class="join j2" cx="${X0 + 2 * S - S / 2}" cy="${Y0 + 2 * S + DEPTH / 2}" r="7"/>
    <circle class="join j3" cx="${X0 + S + DEPTH / 2}" cy="${cy}" r="7"/>
    <circle class="join j4" cx="${X0 + 2 * S - DEPTH / 2}" cy="${cy}" r="7"/>
  </g>`;

const overlayFile = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1200 800" width="1200" height="800" preserveAspectRatio="xMidYMid meet">
  <!--
    BP-04 Blueprint connection overlay. Generated by tools/build-hero-layers.mjs. Do not edit by hand.
    Layered over blueprint-hero.svg (same viewBox). Paths draw once, then settle; nodes fill as each
    path completes. No continuous glow, no particles. Under prefers-reduced-motion the settled state
    shows immediately. index.html carries the same geometry inline so the page controls the motion.
  -->
  <style>
    .trace { stroke-dasharray: 1; stroke-dashoffset: 1; animation: draw 1.1s cubic-bezier(.4,0,.2,1) forwards; }
    .t2 { animation-delay: .5s; } .t3 { animation-delay: 1.0s; } .t4 { animation-delay: 1.5s; }
    .join { opacity: 0; animation: settle .4s ease forwards; }
    .j1 { animation-delay: 1.0s; } .j2 { animation-delay: 1.5s; } .j3 { animation-delay: 2.0s; } .j4 { animation-delay: 2.5s; }
    @keyframes draw { to { stroke-dashoffset: 0; } }
    @keyframes settle { to { opacity: 1; } }
    @media (prefers-reduced-motion: reduce) { .trace { animation: none; stroke-dashoffset: 0; } .join { animation: none; opacity: 1; } }
  </style>
${overlayShapes}
</svg>
`;

writeFileSync(resolve(dir, 'blueprint-hero.svg'), field);
writeFileSync(resolve(dir, 'blueprint-connections.svg'), overlayFile);

const indexPath = resolve(root, 'index.html');
const index = readFileSync(indexPath, 'utf8');
const start = '<!-- bp-connections:start (generated by tools/build-hero-layers.mjs; do not edit) -->';
const end = '<!-- bp-connections:end -->';
const inline = `${start}
        <svg class="connections" viewBox="0 0 1200 800" preserveAspectRatio="xMidYMid meet" focusable="false" aria-hidden="true">
${overlayShapes.replace(/^/gm, '        ')}
        </svg>
        ${end}`;
const re = new RegExp(`${start.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${end.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}`);
if (!re.test(index)) throw new Error('index.html is missing the bp-connections markers');
writeFileSync(indexPath, index.replace(re, inline));
console.log('wrote blueprint-hero.svg, blueprint-connections.svg, and inline overlay in index.html');
