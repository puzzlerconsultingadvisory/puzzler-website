// Derives the seven Method state exports, the static fallback, and the page
// stylesheet from the single grouped master. Run: npm run build:method
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { LAYERS, STATES, COMPLETE } from './method-states.config.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const dir = resolve(here, '../website-assets/blueprint/method');
const master = readFileSync(resolve(dir, 'puzzler-method-master.svg'), 'utf8');

for (const id of LAYERS) {
  if (!master.includes(`id="${id}"`)) throw new Error(`Master is missing layer ${id}`);
}

const pad = (n) => String(n).padStart(2, '0');

function stateStyle(layers) {
  return LAYERS.map((id) => `#${id}{opacity:${layers[id] ?? 0}}`).join('');
}

function deriveSvg(state, filename, title) {
  // Static export: embed a <style> that fixes each layer's opacity. No animation.
  const style = `\n  <style>${stateStyle(state.layers)}</style>`;
  let svg = master
    .replace(/<!--[\s\S]*?-->\s*/g, '') // strip master comments
    .replace(/<title id="pm-title">[^<]*<\/title>/, `<title id="pm-title">${title}</title>`)
    .replace(/<desc id="pm-desc">[^<]*<\/desc>/, `<desc id="pm-desc">${state.shown}.</desc>`)
    .replace(/<desc id="pm-desc">[^<]*<\/desc>/, (m) => m + style)
    .replace(/ class="puzzler-method"/, ` class="puzzler-method method-${state.slug}"`);
  svg = `<!-- Derived from puzzler-method-master.svg by tools/build-method-states.mjs. Do not edit by hand. -->\n` + svg;
  writeFileSync(resolve(dir, filename), svg);
  console.log('wrote', filename);
}

for (const s of STATES) {
  deriveSvg(s, `method-state-${pad(s.n)}-${s.slug}.svg`, `The Puzzler Method, step ${s.n}: ${s.name}`);
}
deriveSvg(COMPLETE, 'method-complete-static.svg', 'The Puzzler Method, complete');

// Page stylesheet: same opacities keyed by data-state, plus disciplined transitions
// and the one-time edge trace for step 1. Reduced-motion users never receive this
// stylesheet's animated path (index.html swaps to the static exports instead).
let css = `/* Generated by tools/build-method-states.mjs from method-states.config.mjs. Do not edit by hand. */\n`;
css += `.method-stage svg [id^="g-"]{opacity:0;transition:opacity .6s ease}\n`;
for (const s of STATES) {
  const sel = `.method-stage[data-state="${s.n}"]`;
  css += `${sel} ${LAYERS.filter((id) => s.layers[id] != null).map((id) => `#${id}`).join(`,${sel} `)}{}\n`;
  for (const id of LAYERS) {
    const v = s.layers[id];
    if (v != null) css += `${sel} #${id}{opacity:${v}}\n`;
  }
}
const cSel = `.method-stage[data-state="complete"]`;
for (const id of LAYERS) {
  const v = COMPLETE.layers[id];
  if (v != null) css += `${cSel} #${id}{opacity:${v}}\n`;
}
css += `/* One-time trace: edges draw once when step 1 is shown, then settle. */\n`;
css += `.method-stage svg #g-edge path{stroke-dasharray:1;stroke-dashoffset:1}\n`;
css += `.method-stage[data-state="1"] #g-edge path{animation:pm-trace .7s ease forwards}\n`;
css += `.method-stage[data-state="1"] #g-edge path:nth-child(2){animation-delay:.55s}\n`;
css += `.method-stage[data-state="1"] #g-edge path:nth-child(3){animation-delay:1.1s}\n`;
css += `.method-stage[data-state="1"] #g-edge path:nth-child(4){animation-delay:1.65s}\n`;
css += `.method-stage[data-state="4"] #g-cues path{stroke-dasharray:1;stroke-dashoffset:1;animation:pm-trace 1.1s ease forwards}\n`;
css += `@keyframes pm-trace{to{stroke-dashoffset:0}}\n`;
css += `@media (prefers-reduced-motion: reduce){.method-stage svg [id^="g-"]{transition:none}.method-stage svg #g-edge path,.method-stage svg #g-cues path{animation:none;stroke-dashoffset:0}}\n`;
writeFileSync(resolve(dir, 'method-states.css'), css.replace(/\{\}\n/g, '\n').replace(/^\.method-stage\[data-state="\d"\] #g-[^\n]*,[^\n]*\n/gm, ''));
console.log('wrote method-states.css');
